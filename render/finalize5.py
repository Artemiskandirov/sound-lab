import json
import sys

sys.path.insert(0, '.')
import haptics_dense as HD

BASE = '../'
man = json.load(open(BASE + 'sounds.json', encoding='utf-8'))
sounds = man['sounds']

ticks = {s['id']: HD.switch_ticks(s['env'], s['envStepMs']) for s in sounds}
total_ticks = sum(len(v) for v in ticks.values())
long_ones = [s for s in sounds if s['durationMs'] >= 1000]

build = json.load(open(BASE + 'build.json', encoding='utf-8'))
build.update({
    'version': '13.6.0',
    'build': '2026-09-01-ios-switch-train',
    'iosSwitchTicks': total_ticks,
    'iosSwitchTickMinMs': int(HD.TICK_MIN_MS),
    'iosSwitchTickMaxMs': int(HD.TICK_MAX_MS),
})
json.dump(build, open(BASE + 'build.json', 'w', encoding='utf-8'),
          ensure_ascii=False, indent=2)

rows = []
for sid in ['tap', 'wood-knock', 'level-up', 'grand-prize', 'marathon-win']:
    s = next(x for x in sounds if x['id'] == sid)
    t = ticks[sid]
    gaps = [t[i + 1] - t[i] for i in range(len(t) - 1)] or [0]
    gaps.sort()
    rows.append(f"| {s['title']} | {s['durationMs']} мс | {len(s['dense'])} | "
                f"**{len(t)}** | {gaps[len(gaps) // 2]} мс |")

readme = open(BASE + 'README.md', encoding='utf-8').read()
readme += '''

---

# v13.6 — на iPhone длинная вибрация собирается из щелчков переключателя

## В чём была ошибка

Прошлая версия на iOS делала одно нажатие скрытого
`<input type="checkbox" switch>` — один системный щелчок на жест — и на этом
останавливалась. В комментарии у меня было написано, что отложенные по таймеру
переключения игнорируются. Проверить это на реальном iPhone я не мог и принял
предположение за факт. В результате вся работа над формой вибрации на iPhone не
доезжала: там оставался один тычок в начале.

## Что теперь

Щелчок переключателя — это не «замена вибрации», это **единица, из которой она
складывается**. Модуль держит пул из четырёх скрытых переключателей и дёргает
их по очереди, а частота дёрганья идёт за огибающей звука:

| громкость | интервал | как ощущается |
|---|---|---|
| близко к пику | 26–35 мс | сплошной гул |
| средняя | 35–60 мс | плотная фактура |
| тихий хвост | 60–90 мс | отдельные тычки |
| тишина | щелчков нет | пауза |

Ниже 26 мс система склеивает щелчки в один, выше 90 мс они перестают читаться
как непрерывность — между этими границами и живёт ощущение длительности.

| звук | длина | импульсов дорожки | переключений | медианный интервал |
|---|---|---|---|---|
''' + '\n'.join(rows) + f'''

По всей библиотеке — **{total_ticks} переключений**.

## Почему по огибающей, а не по дорожке импульсов

Первая версия этого механизма разворачивала в щелчки готовую дорожку вибро. Не
сработало: дорожка разрежённая, между её импульсами по 200–300 мс пустоты, и на
победе в марафоне вышло 56 щелчков со средним интервалом в сотню миллисекунд —
это снова пунктир, а не длительность.

Поэтому в манифест добавлена сама огибающая: уровни по кадрам в 32 мс, в
децибелах относительно пика. Расписание щелчков строится из неё непрерывно —
и тогда у марафона {len(ticks['marathon-win'])} переключений с медианным
интервалом в 33 мс, то есть настоящая длинная вибрация, которая гаснет вместе
со звуком.

## Почему requestAnimationFrame, а не setTimeout

Цепочка таймеров на 26–30 мс копит дрейф и за секунду уезжает от звука на
десятки миллисекунд. Кадровый цикл сверяется с абсолютным временем и опоздания
не накапливает. Первый щелчок отправляется синхронно, внутри самого жеста — в
WebKit это единственный момент, когда хаптик гарантированно проходит.

Плата за это: на экране 60 Гц чаще одного щелчка в кадр не выдать, то есть
практический потолок — примерно 33 мс между щелчками. Это внутри полосы
«сплошного гула», но на 120-герцевом ProMotion получится плотнее.

## Как проверить

В карточке «Вибро в браузере» появился переключатель **Движок**: «Авто»,
«Vibration API», «Переключатель (iOS)». Третий режим включает серию щелчков
принудительно на любом устройстве — на Android это слышно рукой как дребезг, и
видно в диагностике счётчиком отправленных щелчков.

Рядом кнопки «держать 0,5 с», «держать 2 с», «фактура 2 с» — ровная серия без
привязки к звуку, чтобы понять, что конкретное устройство вообще отрабатывает.

В карточке экспорта у каждого звука — кнопка **«Проиграть как на iOS»**, а в
скачиваемом `.js` рядом с чанками для `navigator.vibrate` лежит готовое
расписание `ticks` и цикл, который его играет.

## Честно про ограничения

Apple нигде не обещает хаптик на программное переключение — это обход, а не
документированный API. На части устройств, при включённом «Уменьшении движения»
и в фоне серия может не отработать целиком. Проверить это из контейнера я не
могу: iPhone у меня нет, а WebKit в headless-сборке системный хаптик не
эмулирует. Что проверено машинно: все запланированные щелчки доходят до
элементов, фактический интервал не опускается ниже 24 мс (иначе система склеит
два щелчка в один), расписание не уезжает от звука, а на устройствах с
`navigator.vibrate` путь остался прежним — чанками, без переключателей.
'''
open(BASE + 'README.md', 'w', encoding='utf-8').write(readme)
print('щелчков всего:', total_ticks, '| длинных звуков:', len(long_ones))
